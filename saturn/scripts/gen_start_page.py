"""Packs the Saturn start page (saturn://start) into a C++ header.

The page's files live in
  chrome/browser/ui/webui/saturn_start/resources/
and are served by saturn_start_ui.cc from saturn_start_page.h, which this
script writes. Run it after editing the page:

  python saturn/scripts/gen_start_page.py <chromium src dir>

start.js is built from _ink.txt (the art's logo grid) + start_tail.js.
"""
import os
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(__file__), '..', '..', 'ungoogled-chromium-windows',
    'build', 'src')
d = os.path.join(src, 'chrome', 'browser', 'ui', 'webui', 'saturn_start')
res = os.path.join(d, 'resources')


def read(name):
    with open(os.path.join(res, name), encoding='utf-8') as f:
        return f.read()


js = read('_ink.txt') + '\n' + read('start_tail.js')
with open(os.path.join(res, 'start.js'), 'w', encoding='utf-8',
          newline='\n') as f:
    f.write(js)

files = [('kHtml', read('start.html')), ('kCss', read('start.css')),
         ('kJs', js), ('kSearchSvg', read('search.svg'))]

DELIM = 'SATURN'
out = ['// Copyright 2026 The Saturn Authors',
       '// Use of this source code is governed by a BSD-style license that can be',
       '// found in the LICENSE file.', '',
       '// Generated by saturn/scripts/gen_start_page.py from resources/. Do not',
       '// edit by hand.', '',
       '#ifndef CHROME_BROWSER_UI_WEBUI_SATURN_START_SATURN_START_PAGE_H_',
       '#define CHROME_BROWSER_UI_WEBUI_SATURN_START_SATURN_START_PAGE_H_', '',
       'namespace saturn_start {', '']
for name, text in files:
    assert ')' + DELIM + '"' not in text
    chunks = [text[i:i + 8000] for i in range(0, len(text), 8000)] or ['']
    out.append('inline constexpr char %s[] =' % name)
    for c in chunks:
        out.append('    R"%s(%s)%s"' % (DELIM, c, DELIM))
    out[-1] += ';'
    out.append('')
out += ['}  // namespace saturn_start', '',
        '#endif  // CHROME_BROWSER_UI_WEBUI_SATURN_START_SATURN_START_PAGE_H_',
        '']
with open(os.path.join(d, 'saturn_start_page.h'), 'w', encoding='utf-8',
          newline='\n') as f:
    f.write('\n'.join(out))
print('wrote saturn_start_page.h')
